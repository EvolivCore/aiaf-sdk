"""The shared conformance vectors, replayed against the Python reference verifier.

The Node and Go SDKs replay ``sdk/testdata/vectors.json`` and must reach these verdicts. The
vectors are generated by Python, so this suite checks the generator and the reference agree — and
it covers the multi-step ``sequences``, which pin replay-cache behaviour no single request shows.
"""

from __future__ import annotations

import json
import os
from datetime import datetime, timezone
from pathlib import Path
from unittest.mock import patch

import pytest

from aidr_verifier import AgentVerifier, NonceCache, VerificationPolicy, build_trust_store

# AIDR_VECTORS: replay another signer's vectors (the conformance gate, docs/13); default the
# committed reference vectors.
VECTORS = json.loads(Path(os.environ.get("AIDR_VECTORS") or
                          Path(__file__).resolve().parents[1] / "sdk" / "testdata" / "vectors.json")
                     .read_text(encoding="utf-8"))
AT = datetime.fromtimestamp(VECTORS["evaluate_at"], tz=timezone.utc)


def verifier_for(suite: dict, case: dict) -> AgentVerifier:
    with patch("aidr_crypto.jws.utcnow", lambda: AT):     # the deltas are time-bound too
        trust = build_trust_store(suite["jwks"], expected_issuer=suite["issuer"],
                                  delta_token=suite["revocation"]["delta_before_revocation"])
    policy = VerificationPolicy(expected_issuer=suite["issuer"],
                                expected_audience=case.get("expected_audience"),
                                min_assurance=case.get("min_assurance", 0))
    return AgentVerifier(trust, policy=policy, nonce_seen=NonceCache())


def check(verifier: AgentVerifier, case: dict, expect: str, code: str | None, suite: dict):
    at = datetime.fromtimestamp(case["evaluate_at"], tz=timezone.utc) if "evaluate_at" in case else AT
    result, error = verifier.try_verify(method=case["method"], url=case["url"],
                                        headers=case["headers"], now=at)
    if expect == "allow":
        assert error is None, f"{error.code}: {error.message}"
        assert result.aid == suite["aid"]
        assert result.assurance == suite["expected_assurance"]
        assert (result.agal, result.oal, result.kal) == \
            (suite["expected_agal"], suite["expected_oal"], suite["expected_kal"])
    else:
        assert result is None
        if code:
            assert error.code == code


@pytest.mark.parametrize(("suite", "case"), [
    pytest.param(s, c, id=f"{s['algorithm']}: {c['name']}")
    for s in VECTORS["suites"] for c in s["cases"]])
def test_case(suite, case):
    check(verifier_for(suite, case), case, case["expect"], case.get("expect_code"), suite)


@pytest.mark.parametrize(("suite", "sequence"), [
    pytest.param(s, q, id=f"{s['algorithm']}: {q['name']}")
    for s in VECTORS["suites"] for q in s["sequences"]])
def test_sequence(suite, sequence):
    cases = {c["name"]: c for c in suite["cases"]}
    verifier = verifier_for(suite, {})
    for step in sequence["steps"]:
        check(verifier, cases[step["case"]], step["expect"], step.get("expect_code"), suite)


@pytest.mark.parametrize(("suite", "case"), [
    pytest.param(s, c, id=f"{s['algorithm']}: {c['name']}")
    for s in VECTORS["suites"] for c in s["freshness_cases"]])
def test_freshness_case(suite, case):
    """Trust loaded at evaluate_at, the request verified at the case's own, later instant."""
    assert suite["max_revocation_age_seconds"] == 660
    check(verifier_for(suite, case), case, case["expect"], case.get("expect_code"), suite)
